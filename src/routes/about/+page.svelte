<h2>Mystler's Goal Projection Tool</h2>

<p>
  This tool is a basic custom prediction model for national team soccer games. It is written with Svelte, TypeScript,
  Tailwind CSS, and Font Awesome. The source code is available on <a
    href="https://github.com/Mystler/goal-prediction"
    target="_blank"
    rel="noopener">GitHub</a
  >.
</p>
<p>
  The data source for all past game results is the GitHub repository at <a
    href="https://github.com/martj42/international_results"
    target="_blank"
    rel="noopener">martj42/international_results</a
  >.
</p>
<p>
  Custom ELO calculations for all teams are inspired by <a href="https://eloratings.net" target="_blank" rel="noopener"
    >eloratings.net</a
  >.
</p>
<p>
  The approach to projected goal calculations is inspired by <a href="https://xgscore.io" target="_blank" rel="noopener"
    >xgscore.io</a
  >.
</p>
